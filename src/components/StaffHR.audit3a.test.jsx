import { beforeEach, afterEach, it, expect, vi } from 'vitest'
import { render, screen, cleanup, fireEvent } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
const svc = vi.hoisted(() => ({ runs: vi.fn(), detail: vi.fn(), advance: vi.fn(), update: vi.fn(), overlap: vi.fn(), create: vi.fn(), staff: vi.fn(), outstanding: vi.fn(), leave: vi.fn() }))
vi.mock('../lib/supabase', async () => {
  const { createSupabaseMock } = await import('../test/supabaseMock')
  return { supabase: createSupabaseMock(() => ({ data: [], error: null })).supabase }
})
vi.mock('pdfjs-dist', () => ({ GlobalWorkerOptions: {} }))
vi.mock('../services/attendance', () => ({ attendanceService: { getCountsByRange: async () => ({}) }, payrollService: { getRuns: svc.runs, getRunWithLines: svc.detail, advanceRun: svc.advance, updateLine: svc.update, checkOverlap: svc.overlap, createRun: svc.create } }))
vi.mock('../services/staff', () => ({ staffService: { getActive: svc.staff } }))
vi.mock('../services/advances', () => ({ advancesService: { getOutstandingByStaff: svc.outstanding } }))
vi.mock('../services/leave', () => ({ leaveService: { getUnpaidApprovedOverlapping: svc.leave } }))
import { PayrollTab } from './StaffHR'
const run = { id: 'r', period_from: '2026-01-01', period_to: '2026-01-31', status: 'md_approved', total_payroll: 10000 }
const line = { id: 'l', staff: { full_name: 'TEST worker' }, amount_due: 10000, deductions: 500, amount_paid: 0 }
afterEach(cleanup)
beforeEach(() => {
  vi.clearAllMocks()
  svc.runs.mockResolvedValue([run]); svc.detail.mockResolvedValue({ run, lines: [line] })
  svc.advance.mockResolvedValue({ id: 'r' }); svc.update.mockResolvedValue({ id: 'l' }); svc.overlap.mockResolvedValue(undefined)
  svc.staff.mockResolvedValue([{ id: 's', full_name: 'TEST worker', staff_type: 'permanent', monthly_salary: 31000 }])
  svc.outstanding.mockResolvedValue({ s: [{ id: 'a', outstanding_balance: 800, installment_amount: 5000 }] })
  svc.leave.mockResolvedValue({}); svc.create.mockResolvedValue({ id: 'r' })
})
const open = async role => {
  render(<PayrollTab userProfile={{ role }} approvalsOnly />)
  await userEvent.click(await screen.findByRole('button', { name: 'View', exact: true }))
  await screen.findByText('TEST worker')
}
it('9: accountant sees payroll approvals only and can record MD-approved payment fields', async () => {
  await open('accountant')
  expect(screen.queryByRole('button', { name: 'New Payroll Run' })).toBeNull()
  expect(screen.queryByRole('button', { name: 'Staff Directory' })).toBeNull()
  expect(screen.queryByText('Onboarding')).toBeNull()
  expect(screen.getByRole('spinbutton')).toHaveValue(0)
  await userEvent.click(screen.getByRole('button', { name: 'Record Payments & Mark Paid' }))
  expect(await screen.findByText('Payments recorded — payroll marked as PAID.')).toBeInTheDocument()
  expect(svc.update).toHaveBeenCalledWith('l', expect.objectContaining({ amount_paid: 0 }))
  expect(svc.advance).toHaveBeenCalledWith('r','mark_paid')
})
it('9: MD-approved run disables MD payment with the accountant hand-off explanation', async () => {
  render(<PayrollTab userProfile={{ role: 'md' }} approvalsOnly />)
  await userEvent.click(await screen.findByRole('button', { name: 'View', exact: true }))
  const button = await screen.findByRole('button', { name: 'Mark paid (accountant)' })
  expect(button).toBeDisabled()
  expect(screen.getByText('The MD who approved this run cannot also mark it paid; the accountant must complete payment.')).toBeInTheDocument()
  expect(screen.queryByRole('spinbutton')).toBeNull()
})
it.each(['ico_approved','paid'])('9: %s salary amounts and payment fields remain read-only', async status => {
  svc.detail.mockResolvedValue({ run: { ...run, status }, lines: [line] })
  await open('accountant')
  expect(screen.queryByRole('spinbutton')).toBeNull()
  expect(screen.queryByRole('button', { name: 'Record Payments & Mark Paid' })).toBeNull()
})
it('9: ICO can approve a draft and cannot prepare a salary run', async () => {
  svc.detail.mockResolvedValue({ run: { ...run, status: 'draft' }, lines: [line] })
  await open('ico')
  expect(screen.queryByRole('button', { name: 'New Payroll Run' })).toBeNull()
  await userEvent.click(screen.getByRole('button', { name: 'ICO Approve' }))
  expect(svc.advance).toHaveBeenCalledWith('r','ico_approve',null)
  expect(svc.update).not.toHaveBeenCalled()
})
it('9/14: refused accountant line payment shows the database message without marking paid', async () => {
  svc.update.mockRejectedValue(new Error('TEST payment refused'))
  await open('accountant')
  await userEvent.click(screen.getByRole('button', { name: 'Record Payments & Mark Paid' }))
  expect(await screen.findByText('Failed to record payments: TEST payment refused')).toBeInTheDocument()
  expect(svc.advance).not.toHaveBeenCalled()
})
it('10: HR deduction form caps to the named advance and saves salary_advance_id', async () => {
  render(<PayrollTab userProfile={{ role: 'hr_officer' }} />)
  fireEvent.change(screen.getByText('Period From').parentElement.querySelector('input'), { target: { value: '2026-01-01' } })
  fireEvent.change(screen.getByText('Period To').parentElement.querySelector('input'), { target: { value: '2026-01-31' } })
  await userEvent.click(screen.getByRole('button', { name: 'Calculate Payroll' }))
  const input = await screen.findByRole('spinbutton', { name: 'Advance deduction for TEST worker' })
  expect(input).toHaveValue(800)
  fireEvent.change(input, { target: { value: '9000' } })
  expect(input).toHaveValue(800)
  expect(screen.getByText(/Capped at 800/)).toBeInTheDocument()
  await userEvent.click(screen.getByRole('button', { name: 'Approve Payroll' }))
  await userEvent.click(screen.getByRole('button', { name: 'Approve & Save Payroll' }))
  expect(svc.create).toHaveBeenCalledWith(expect.anything(), [expect.objectContaining({ salary_advance_id: 'a', advance_deduction: 800 })])
})
it('10: HR must choose among multiple disbursed advances', async () => {
  svc.outstanding.mockResolvedValue({ s: [{ id: 'a', outstanding_balance: 800, installment_amount: 500 }, { id: 'b', outstanding_balance: 1000, installment_amount: 500 }] })
  render(<PayrollTab userProfile={{ role: 'hr_officer' }} />)
  await userEvent.click(screen.getByRole('button', { name: 'Calculate Payroll' }))
  const picker = await screen.findByRole('combobox', { name: 'Advance for TEST worker' })
  expect(picker).toHaveValue('')
  expect(screen.getByRole('spinbutton', { name: 'Advance deduction for TEST worker' })).toBeDisabled()
  await userEvent.selectOptions(picker,'b')
  expect(screen.getByRole('spinbutton', { name: 'Advance deduction for TEST worker' })).toHaveValue(500)
})
it('8a: overlap preflight error is displayed and prevents calculation/generation', async () => {
  svc.overlap.mockRejectedValue(new Error('A salary run already covers 2026-01-01 to 2026-01-31'))
  render(<PayrollTab userProfile={{ role: 'hr_officer' }} />)
  await userEvent.click(screen.getByRole('button', { name: 'Calculate Payroll' }))
  expect(await screen.findByText(/A salary run already covers 2026-01-01 to 2026-01-31/)).toBeInTheDocument()
  expect(svc.create).not.toHaveBeenCalled()
  expect(screen.queryByRole('button', { name: 'Approve Payroll' })).toBeNull()
})
it('14: failed salary detail fetch cannot expose payment controls for stale lines', async () => {
  svc.detail.mockRejectedValue(new Error('TEST lines denied'))
  render(<PayrollTab userProfile={{ role: 'accountant' }} approvalsOnly />)
  await userEvent.click(await screen.findByRole('button', { name: 'View', exact: true }))
  expect(await screen.findByText('TEST lines denied')).toBeInTheDocument()
  expect(screen.queryByRole('button', { name: 'Record Payments & Mark Paid' })).toBeNull()
  expect(svc.update).not.toHaveBeenCalled()
})
